// =============================================================================
// services/favoritesDb.js
// -----------------------------------------------------------------------------
// Requirement #5 — network requests that CREATE / READ / DELETE data in our
// own database (Firebase Cloud Firestore).
//
// Firestore stores data as "documents" (like JSON objects) grouped into
// "collections" (like folders). We use ONE collection called "favorites".
// Each document in it is one space picture the user saved:
//
//   favorites/                      <- collection
//     aB3xYz.../                    <- document (id generated by Firebase)
//       { date, title, url, mediaType, explanation, savedAt }
//
// Every function below is `async` because each one is a network request to
// Google's servers — the app has to WAIT for the answer.
// =============================================================================

import {
  collection,
  addDoc,
  getDocs,
  deleteDoc,
  doc,
  query,
  orderBy,
} from 'firebase/firestore';
import { db } from './firebase';

// A reference (a "pointer") to the favorites collection. Nothing is downloaded
// yet — this just says WHERE in the database we are going to work.
const favoritesCollection = collection(db, 'favorites');

// -----------------------------------------------------------------------------
// CREATE — save one picture to the database.
// Returns the full saved object, INCLUDING the new id Firebase generated.
// We need that id later so we know which document to delete.
// -----------------------------------------------------------------------------
export async function createFavorite(apod) {
  // Only keep the fields we actually need (smaller documents = faster).
  const newFavorite = {
    date: apod.date,
    title: apod.title,
    url: apod.url,
    mediaType: apod.mediaType,
    explanation: apod.explanation,
    savedAt: Date.now(), // a timestamp so we can sort newest-first
  };

  // addDoc sends the data to Firestore and waits for confirmation.
  const docRef = await addDoc(favoritesCollection, newFavorite);

  // Hand back the object with its id attached, ready to put in local state.
  return { id: docRef.id, ...newFavorite };
}

// -----------------------------------------------------------------------------
// READ — download every saved picture, newest first.
// -----------------------------------------------------------------------------
export async function readFavorites() {
  const newestFirst = query(favoritesCollection, orderBy('savedAt', 'desc'));
  const snapshot = await getDocs(newestFirst);

  // A "snapshot" is Firestore's wrapper around the results. We turn each
  // document into a plain JavaScript object: { id, ...fields }.
  return snapshot.docs.map((document) => ({
    id: document.id,
    ...document.data(),
  }));
}

// -----------------------------------------------------------------------------
// DELETE — remove one picture from the database, using its document id.
// -----------------------------------------------------------------------------
export async function deleteFavorite(id) {
  await deleteDoc(doc(db, 'favorites', id));
}
